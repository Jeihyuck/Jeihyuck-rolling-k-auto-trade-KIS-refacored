"""Independent, read-only KR session watchdog; never orders or restarts workers.

The WSL AM/PM wrapper launches it outside the trading lock. A local warning is
not proof of a broker fault. It watches the exact current run, not a prior
successful manifest entry. Only the existing single writer may submit.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re
import time

_TICK = re.compile(r"\[PB1\]\[TICK\]\[DONE\].*?\bnow=([^\s]+)")
_TERMINAL = {"OK", "OK_WITH_WARNINGS", "WARN", "DEGRADED", "FAILED", "FAIL",
             "TIMEOUT", "RETRYABLE_DEGRADED", "SKIPPED_NON_TRADING_DAY", "SKIP_DUPLICATE"}


def _stamp(value):
    try:
        dt = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
        return dt if dt.tzinfo else None
    except (ValueError, TypeError):
        return None


def _tail(path, limit=262144):
    try:
        with path.open("rb") as f:
            f.seek(0, 2)
            f.seek(max(0, f.tell()-limit))
            return f.read(limit).decode("utf-8", errors="replace")
    except OSError:
        return ""


def inspect(*, root, trade_date, session, run_id, started, now,
            parent_alive=True, observer_required=True, max_tick_age=240):
    partition = Path(root)/"runtime"/"logs"/"kr"/trade_date
    manifest = partition/"session-manifest.json"
    try:
        data = json.loads(manifest.read_text(encoding="utf-8"))
        attempts = data["sessions"][session]["attempts"]
        match = [a for a in attempts if a.get("run_id") == run_id]
        attempt = match[0] if len(match) == 1 else {}
    except (OSError, ValueError, TypeError, KeyError, AttributeError):
        attempt = {}
    status = str(attempt.get("status") or "UNKNOWN").upper()
    if status in _TERMINAL:
        return {"state": "TERMINAL", "session_status": status, "alerts": []}
    elapsed = max(0., (now-started).total_seconds())
    alerts = []
    if not parent_alive:
        alerts.append("SESSION_PARENT_EXITED_WITHOUT_TERMINAL")
    if elapsed >= max_tick_age and not attempt:
        alerts.append("CURRENT_SESSION_MANIFEST_UNVERIFIED")
    # The current run id is generated by init-session-log.sh, not the
    # effective_run_id from a prior successful attempt.
    log = partition/session/(run_id+".log")
    ticks = [_stamp(x) for x in _TICK.findall(_tail(log))]
    valid = [x for x in ticks if x and started <= x <= now]
    age = (now-max(valid)).total_seconds() if valid else elapsed
    if elapsed >= max_tick_age and age >= max_tick_age:
        alerts.append("TICK_COMPLETION_STALE")
    if observer_required and elapsed >= max_tick_age:
        observer = partition/"kr-opening-observer.log"
        try:
            observer_age = now.timestamp()-observer.stat().st_mtime
        except OSError:
            observer_age = None
        if observer_age is None or not 0 <= observer_age <= max_tick_age:
            alerts.append("OBSERVER_LOG_STALE_OR_MISSING")
    return {"state": "WARNING" if alerts else "MONITORING", "session_status": status,
            "last_tick_completion_age_sec": round(age, 1), "alerts": alerts}


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--date", required=True)
    parser.add_argument("--session", choices=["am","afternoon"], required=True)
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--parent-pid", type=int, required=True)
    parser.add_argument("--observer-required", choices=["0","1"], default="1")
    parser.add_argument("--max-tick-age", type=int, default=420)
    args = parser.parse_args(argv)
    if (not re.fullmatch(r"[A-Za-z0-9_.-]+", args.run_id)
            or args.run_id in {".",".."} or args.parent_pid <= 1):
        parser.error("invalid session identity")
    datetime.strptime(args.date,"%Y-%m-%d")
    if os.getenv("KIS_ENV") != "practice" or os.getenv("NO_TRADE") != "1":
        raise RuntimeError("PRACTICE_READ_ONLY_REQUIRED")
    started = datetime.now(timezone.utc)
    last = None
    while (datetime.now(timezone.utc)-started).total_seconds() < 24000:
        try:
            os.kill(args.parent_pid,0)
            alive = True
        except ProcessLookupError:
            alive = False
        except PermissionError:
            alive = True
        result = inspect(root=Path.cwd(), trade_date=args.date, session=args.session,
                         run_id=args.run_id, started=started, now=datetime.now(timezone.utc),
                         parent_alive=alive, observer_required=args.observer_required=="1",
                         max_tick_age=max(240,min(900,args.max_tick_age)))
        key = (result["state"], tuple(result["alerts"]))
        if key != last:
            print("[KR][SESSION_WATCHDOG] "+json.dumps(
                {"date":args.date,"session":args.session,"run_id":args.run_id,
                 "observed_at":datetime.now(timezone.utc).isoformat(),**result},
                sort_keys=True), flush=True)
            last = key
        if result["state"] == "TERMINAL" or not alive:
            return
        time.sleep(20)


if __name__ == "__main__":
    main()
